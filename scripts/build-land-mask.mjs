// Rasterises Natural Earth land polygons (public domain, via the `world-atlas` package)
// into a 1-degree equirectangular bitmask, run-length encoded.
// The globe samples this mask at runtime to place its continent dots.
//
// Usage: node scripts/build-land-mask.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

import { feature } from "topojson-client";

const WIDTH = 360;
const HEIGHT = 180;
// Antarctica clutters the silhouette and carries no story value for this site.
const MIN_LATITUDE = -58;

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const topology = JSON.parse(readFileSync(resolve(root, "node_modules/world-atlas/land-110m.json"), "utf8"));
const land = feature(topology, topology.objects.land);
const polygons = [];
for (const f of land.features ?? [land]) {
  const geometry = f.geometry;
  if (geometry.type === "Polygon") polygons.push(geometry.coordinates);
  else if (geometry.type === "MultiPolygon") polygons.push(...geometry.coordinates);
}

const bounds = polygons.map((rings) => {
  let minX = Infinity,
    minY = Infinity,
    maxX = -Infinity,
    maxY = -Infinity;
  for (const [x, y] of rings[0]) {
    if (x < minX) minX = x;
    if (x > maxX) maxX = x;
    if (y < minY) minY = y;
    if (y > maxY) maxY = y;
  }
  return { minX, minY, maxX, maxY };
});

/** Even-odd ray casting across outer ring + holes. */
function containsPoint(rings, x, y) {
  let inside = false;
  for (const ring of rings) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const [xi, yi] = ring[i];
      const [xj, yj] = ring[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
    }
  }
  return inside;
}

function isLand(lon, lat) {
  if (lat < MIN_LATITUDE) return false;
  for (let p = 0; p < polygons.length; p++) {
    const b = bounds[p];
    if (lon < b.minX || lon > b.maxX || lat < b.minY || lat > b.maxY) continue;
    if (containsPoint(polygons[p], lon, lat)) return true;
  }
  return false;
}

const rows = [];
let landCells = 0;
for (let row = 0; row < HEIGHT; row++) {
  const lat = 90 - (row + 0.5);
  const runs = [];
  let current = false; // runs alternate, starting with water
  let length = 0;
  for (let col = 0; col < WIDTH; col++) {
    const lon = -180 + (col + 0.5);
    const cell = isLand(lon, lat);
    if (cell) landCells++;
    if (cell === current) length++;
    else {
      runs.push(length);
      current = cell;
      length = 1;
    }
  }
  runs.push(length);
  rows.push(runs.join(","));
}

const output = `// AUTO-GENERATED by scripts/build-land-mask.mjs — do not edit by hand.
// Source: Natural Earth 110m land (public domain) via the \`world-atlas\` package.
// Format: one row per degree of latitude (north to south); each row is a comma-separated
// list of run lengths over longitude (west to east), alternating water, land, water, ...

export const LAND_MASK_WIDTH = ${WIDTH};
export const LAND_MASK_HEIGHT = ${HEIGHT};
export const LAND_MASK_ROWS: readonly string[] = ${JSON.stringify(rows)};
`;

const target = resolve(root, "src/features/globe/data/landMask.ts");
writeFileSync(target, output);
console.log(`Wrote ${target}`);
console.log(
  `Land cells: ${landCells} of ${WIDTH * HEIGHT} (${((landCells / (WIDTH * HEIGHT)) * 100).toFixed(1)}%)`,
);
console.log(`File size: ${(output.length / 1024).toFixed(1)} KB`);
